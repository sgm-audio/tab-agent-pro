#!/usr/bin/env python3
"""
Validate index.xml against the ReaPack repository index format.

Background (docs-audit P1-4): the hand-written index used ``version="1.0"``,
no ``commit`` attribute, a ``<description>`` child inside ``<category>``
(not part of the format), ``type`` on ``<version>``, and inverted ``<source>``
elements (the body must be the file to download, and the ``main``/``file``
attribute is the installed filename).

Reference: indexes generated by https://github.com/cfillion/reapack-index,
e.g. https://acendan.github.io/reascripts/index.xml

Usage:
    python tools/check_index.py [path/to/index.xml]

The index is what ReaPack clients install from, so it also fails when the pinned
commit predates the newest change to a published <source>: a green CI with a
stale pin means users get a script the repository no longer ships.

"""

from __future__ import annotations

import datetime as dt
import subprocess  # nosec B404
import sys
import xml.etree.ElementTree as ET  # nosec B405
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# ReaPack::Index::Source::SECTIONS (reapack-index lib/reapack/index/source.rb).
# The `main` attribute selects which Action List section(s) a script appears in.
ACTION_LIST_SECTIONS = {
    "main",
    "midi_editor",
    "midi_inlineeditor",
    "midi_eventlisteditor",
    "mediaexplorer",
    "crossfade_editor",
    "all",
    "windows",
    "darwin",
    "linux",
}


def _tag(element: ET.Element) -> str:
    """Local tag name, ignoring any XML namespace."""
    return element.tag.rsplit("}", 1)[-1]


def _children(element: ET.Element) -> list[ET.Element]:
    return [child for child in element if isinstance(child.tag, str)]


def _findall(element: ET.Element, tag: str) -> list[ET.Element]:
    return [child for child in _children(element) if _tag(child) == tag]


def _commit_exists(sha: str) -> bool:
    """
    True when ``sha`` resolves to an object in the local git repository.

    Skips (returns True) when git or a git repository is unavailable, so the
    check never produces a false failure in a source tarball or in CI checkouts
    that were exported without history.
    """
    try:
        result = subprocess.run(  # nosec B603, B607
            ["git", "-C", str(ROOT), "cat-file", "-t", sha],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return True
    if result.returncode != 0:
        # Outside a git checkout the sha cannot be resolved: do not fail.
        if "not a git repository" in (result.stderr or "").lower():
            return True
        # In a shallow clone the pinned commit may simply not have been
        # fetched even though it exists upstream; do not report a false
        # failure. The full-history CI checkout is where the SHA is verified.
        return _is_shallow()
    return result.stdout.strip() in {"commit", "tree", "tag"}


def _last_commit_touching(path: str) -> str | None:
    """The newest commit in HEAD's history that changed ``path`` (None if unknown)."""
    try:
        result = subprocess.run(  # nosec B603, B607
            ["git", "-C", str(ROOT), "log", "-1", "--format=%H", "HEAD", "--", path],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip() or None


def _is_ancestor(ancestor: str, descendant: str) -> bool | None:
    """Whether ``ancestor`` is contained in ``descendant``'s history (None if unknown)."""
    try:
        result = subprocess.run(  # nosec B603, B607
            ["git", "-C", str(ROOT), "merge-base", "--is-ancestor", ancestor, descendant],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode == 0:
        return True
    if result.returncode == 1:
        return False
    return None


def _is_shallow() -> bool:
    """True when the local checkout is a shallow (depth-limited) clone."""
    try:
        result = subprocess.run(  # nosec B603, B607
            ["git", "-C", str(ROOT), "rev-parse", "--is-shallow-repository"],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0 and result.stdout.strip() == "true"


def _staleness_problems(root: ET.Element, commit: str) -> list[str]:
    """
    Problems where the pinned commit predates a published <source>.

    ReaPack downloads each <source> at the pinned commit, so a pin older than the
    file serves users a script the repository no longer ships — the failure is
    silent, and it is how the 1.0.1 index kept handing out a script that froze
    REAPER for the whole run while main had already been rewritten.
    """
    problems: list[str] = []
    if not commit or not _commit_exists(commit) or _is_shallow():
        return problems
    seen: set[str] = set()
    for category in _findall(root, "category"):
        for package in _findall(category, "reapack"):
            for version in _findall(package, "version"):
                for source in _findall(version, "source"):
                    target = (source.text or "").strip()
                    if not target or target.startswith(("http://", "https://")):
                        continue
                    if target in seen:
                        continue
                    seen.add(target)
                    newest = _last_commit_touching(target)
                    if newest is None or newest == commit:
                        continue
                    if _is_ancestor(newest, commit) is False:
                        problems.append(
                            f"index.xml pins {commit[:8]} but {target} changed in "
                            f"{newest[:8]} — ReaPack clients would install the older "
                            "script; update the commit attribute with the sources"
                        )
    return problems


def check_index(path: Path) -> list[str]:
    """Return a list of human-readable problems (empty means the index is valid)."""
    problems: list[str] = []

    try:
        root = ET.parse(path).getroot()  # nosec B314
    except ET.ParseError as e:
        return [f"index.xml is not well-formed XML: {e}"]

    if _tag(root) != "index":
        problems.append(f"root element is <{root.tag}>, expected <index>")
        return problems

    if root.get("version") != "1":
        problems.append(f'root version="{root.get("version")}" — ReaPack expects version="1"')

    if not root.get("name"):
        problems.append("root is missing the repository name attribute")

    commit = root.get("commit") or ""
    if len(commit) != 40 or any(c not in "0123456789abcdef" for c in commit.lower()):
        problems.append("root is missing a 40-character commit sha (written by reapack-index)")
    elif not _commit_exists(commit):
        # ReaPack resolves every <source> against this sha over raw GitHub, so a
        # stale/unreachable sha means the install silently 404s for end users.
        problems.append(
            f"commit {commit[:8]} does not exist in this repository — every <source> "
            "URL would 404 for ReaPack clients (regenerate the index at release time)"
        )

    problems.extend(_staleness_problems(root, commit))

    for category in _findall(root, "category"):
        # The published format only has <reapack> packages inside a category;
        # anything else (e.g. the old hand-written <description>) is invalid.
        unexpected = [c for c in _children(category) if _tag(c) != "reapack"]
        if unexpected:
            problems.append(
                f"<category name={category.get('name')!r}> has unexpected children "
                f"{[_tag(c) for c in unexpected]}; only <reapack> is allowed"
            )

    packages = [
        package
        for category in _findall(root, "category")
        for package in _findall(category, "reapack")
    ]
    if not packages:
        problems.append("no <reapack> packages found under <category>")

    for package in packages:
        name = package.get("name") or "(unnamed)"
        if package.get("type") != "script":
            problems.append(f"{name}: type={package.get('type')!r}, expected 'script'")
        if not package.get("desc"):
            problems.append(f"{name}: missing desc attribute")

        versions = _findall(package, "version")
        if not versions:
            problems.append(f"{name}: no <version> element")

        for version in versions:
            vname = version.get("name") or "(unnamed)"
            if not version.get("author"):
                problems.append(f"{name} {vname}: missing author")
            if version.get("type") is not None:
                problems.append(f"{name} {vname}: 'type' is not a <version> attribute")
            time = version.get("time") or ""
            if not time.endswith("Z"):
                problems.append(f"{name} {vname}: time={time!r} must be ISO8601 UTC")
            else:
                try:
                    dt.datetime.fromisoformat(time.replace("Z", "+00:00"))
                except ValueError:
                    problems.append(f"{name} {vname}: time={time!r} is not parseable")

            sources = _findall(version, "source")
            if not sources:
                problems.append(f"{name} {vname}: no <source> element")
            for source in sources:
                target = (source.text or "").strip()
                if not target:
                    problems.append(f"{name} {vname}: empty <source>")
                    continue
                # `file` names the filename the package is installed as and is
                # written unconditionally by reapack-index (source.rb: FILE =
                # 'file'). `main` is the *Action List section*, not a filename:
                # its value must be one of SECTIONS or a platform list.
                # Validating only "main or file" is what let a broken index
                # (no file=, main=<filename>) pass this check before.
                if not source.get("file"):
                    problems.append(
                        f"{name} {vname}: <source> needs a file= attribute naming the "
                        "installed filename (reapack-index always writes it)"
                    )
                else:
                    filename = source.get("file") or ""
                    if package.get("type") == "script" and not filename.endswith(".lua"):
                        problems.append(
                            f"{name} {vname}: file={filename!r} is not a .lua script name"
                        )
                    if "/" in filename or "\\" in filename:
                        problems.append(
                            f"{name} {vname}: file={filename!r} must be a bare filename"
                        )
                section = source.get("main")
                if section is not None and section not in ACTION_LIST_SECTIONS:
                    problems.append(
                        f"{name} {vname}: main={section!r} is not an Action List section "
                        f"({', '.join(sorted(ACTION_LIST_SECTIONS))}); the installed "
                        "filename belongs in file="
                    )
                # The body must be a downloadable location: an absolute URL, or a
                # repo-relative path that exists next to the index.
                if target.startswith(("http://", "https://")):
                    if not target.endswith((".lua", ".ext", ".jsfx", ".eel", ".reapack")):
                        problems.append(f"{name} {vname}: unexpected source target {target!r}")
                    if "/raw/" in target and "/main/" in target:
                        problems.append(
                            f"{name} {vname}: source is not commit-pinned ({target!r}); "
                            "regenerate with reapack-index"
                        )
                elif not (ROOT / target).exists():
                    problems.append(f"{name} {vname}: source path not found in repo: {target!r}")

    return problems


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    path = Path(argv[0]) if argv else ROOT / "index.xml"

    problems = check_index(path)
    if problems:
        print(f"{path} is not a valid ReaPack index:")
        for problem in problems:
            print(f"  ✗ {problem}")
        return 1

    root = ET.parse(path).getroot()  # nosec B314
    packages = [
        package
        for category in _findall(root, "category")
        for package in _findall(category, "reapack")
    ]
    print(f"{path.name} OK — {len(packages)} package(s), " f"commit {root.get('commit', '')[:8]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
